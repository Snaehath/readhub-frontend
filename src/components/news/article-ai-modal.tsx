/* eslint-disable @next/next/no-img-element */
"use client";

import Link from "next/link";
import ReactMarkdown from "react-markdown";
import { format, isValid } from "date-fns";
import { AlertCircle, ExternalLink, Eye, Info, Lock, RotateCcw, Sparkles, Telescope } from "lucide-react";
import { Dialog, DialogContent, DialogDescription, DialogTitle } from "../ui/dialog";
import { Button } from "../ui/button";
import { ArticleForecast, ForecastScenario, NewsArticle } from "@/types";
import { ArticleAiMode } from "@/lib/hooks/useArticleAi";
import { InsightBasis } from "@/api/ai";

const MODE_COPY: Record<ArticleAiMode, { label: string; icon: typeof Sparkles; accent: string; loading: string; disclaimer: string; signIn: string }> = {
  explain: {
    label: "AI explainer",
    icon: Sparkles,
    accent: "text-indigo-600 dark:text-indigo-400",
    loading: "Reading the article and preparing context…",
    disclaimer: "AI-generated from this article. Check important details with the publisher.",
    signIn: "Sign in to get an AI explanation and background for this article.",
  },
  forecast: {
    label: "AI forecast",
    icon: Telescope,
    accent: "text-cyan-700 dark:text-cyan-400",
    loading: "Reading the article and mapping possible outcomes…",
    disclaimer: "Speculative scenarios generated by AI. These are possibilities, not predictions.",
    signIn: "Sign in to explore possible outcomes for this story.",
  },
};

const LIKELIHOOD_STYLES: Record<ForecastScenario["likelihood"], string> = {
  high: "bg-emerald-100 text-emerald-900 dark:bg-emerald-950 dark:text-emerald-200",
  medium: "bg-amber-100 text-amber-950 dark:bg-amber-950 dark:text-amber-200",
  low: "bg-zinc-200 text-zinc-800 dark:bg-zinc-800 dark:text-zinc-200",
};

const SCENARIO_ACCENTS: Record<string, string> = {
  "most likely": "border-t-cyan-600",
  optimistic: "border-t-emerald-600",
  pessimistic: "border-t-rose-600",
};

function ForecastView({ forecast }: { forecast: ArticleForecast }) {
  return (
    <div className="space-y-7">
      <section aria-labelledby="forecast-outlook">
        <h3 id="forecast-outlook" className="mb-2 text-sm font-semibold uppercase tracking-wide text-muted-foreground">Where things stand</h3>
        <p className="leading-relaxed">{forecast.outlook}</p>
      </section>

      {forecast.timeline.length > 0 && (
        <section aria-labelledby="forecast-timeline">
          <h3 id="forecast-timeline" className="mb-3 text-sm font-semibold uppercase tracking-wide text-muted-foreground">Timeline</h3>
          <ol className="relative space-y-4 border-l-2 border-cyan-600/30 pl-5">
            {forecast.timeline.map((step) => (
              <li key={step.horizon} className="relative">
                <span className="absolute -left-[27px] top-1 h-3 w-3 rounded-full border-2 border-background bg-cyan-600" aria-hidden="true" />
                <p className="text-sm font-semibold text-cyan-700 dark:text-cyan-400">{step.horizon}</p>
                <p className="text-sm leading-relaxed text-foreground/90">{step.development}</p>
              </li>
            ))}
          </ol>
        </section>
      )}

      <section aria-labelledby="forecast-scenarios">
        <h3 id="forecast-scenarios" className="mb-3 text-sm font-semibold uppercase tracking-wide text-muted-foreground">Scenarios</h3>
        <div className="grid gap-3 md:grid-cols-3">
          {forecast.scenarios.map((scenario) => (
            <article key={scenario.name} className={`flex flex-col rounded-xl border border-t-4 bg-card p-4 ${SCENARIO_ACCENTS[scenario.name.toLowerCase()] || "border-t-primary"}`}>
              <div className="mb-2 flex items-center justify-between gap-2">
                <h4 className="font-semibold">{scenario.name}</h4>
                <span className={`rounded-full px-2 py-0.5 text-[11px] font-semibold capitalize ${LIKELIHOOD_STYLES[scenario.likelihood]}`}>
                  {scenario.likelihood} likelihood
                </span>
              </div>
              <p className="flex-1 text-sm leading-relaxed text-foreground/90">{scenario.summary}</p>
              {scenario.drivers.length > 0 && (
                <ul className="mt-3 flex flex-wrap gap-1.5" aria-label="Key drivers">
                  {scenario.drivers.map((driver) => (
                    <li key={driver} className="rounded-full bg-muted px-2 py-0.5 text-[11px] text-muted-foreground">{driver}</li>
                  ))}
                </ul>
              )}
            </article>
          ))}
        </div>
      </section>

      {forecast.signals.length > 0 && (
        <section aria-labelledby="forecast-signals" className="rounded-xl bg-muted/50 p-4">
          <h3 id="forecast-signals" className="mb-2 flex items-center gap-2 text-sm font-semibold">
            <Eye className="h-4 w-4 text-cyan-700 dark:text-cyan-400" aria-hidden="true" /> Signals to watch
          </h3>
          <ul className="list-disc space-y-1 pl-5 text-sm leading-relaxed">
            {forecast.signals.map((signal) => <li key={signal}>{signal}</li>)}
          </ul>
        </section>
      )}

      {forecast.assumptions.length > 0 && (
        <p className="text-xs leading-relaxed text-muted-foreground">
          <span className="font-semibold">Assumes:</span> {forecast.assumptions.join(" · ")}
        </p>
      )}
    </div>
  );
}

function LoadingState({ message }: { message: string }) {
  return (
    <div role="status" className="space-y-4">
      <p className="text-sm text-muted-foreground">{message}</p>
      <div className="animate-pulse space-y-3" aria-hidden="true">
        <div className="h-4 w-1/3 rounded bg-muted" />
        <div className="h-3.5 w-full rounded bg-muted" />
        <div className="h-3.5 w-11/12 rounded bg-muted" />
        <div className="h-3.5 w-4/5 rounded bg-muted" />
        <div className="h-4 w-1/4 rounded bg-muted pt-4" />
        <div className="h-3.5 w-full rounded bg-muted" />
        <div className="h-3.5 w-3/4 rounded bg-muted" />
      </div>
    </div>
  );
}

interface ArticleAiModalProps {
  article: NewsArticle | null;
  mode: ArticleAiMode;
  explanation: string;
  forecast: ArticleForecast | null;
  basis: InsightBasis | null;
  loading: boolean;
  error: string | null;
  isAuthenticated: boolean;
  onClose: () => void;
  onRetry: () => void;
}

export default function ArticleAiModal({ article, mode, explanation, forecast, basis, loading, error, isAuthenticated, onClose, onRetry }: ArticleAiModalProps) {
  const copy = MODE_COPY[mode];
  const Icon = copy.icon;
  const published = article ? new Date(article.publishedAt) : null;
  const hasResult = mode === "forecast" ? Boolean(forecast) : Boolean(explanation);

  return (
    <Dialog open={Boolean(article)} onOpenChange={(open) => !open && onClose()}>
      <DialogContent className={`flex max-h-[90vh] flex-col gap-0 overflow-hidden p-0 ${mode === "forecast" ? "sm:max-w-4xl" : "sm:max-w-3xl"}`}>
        {article && (
          <>
            <header className="flex gap-4 border-b p-5 pr-12">
              <img
                src={article.urlToImage || "/ReadHub_PlaceHolder.png"}
                alt=""
                referrerPolicy="no-referrer"
                onError={(event) => {
                  event.currentTarget.src = "/ReadHub_PlaceHolder.png";
                }}
                className="hidden h-20 w-28 shrink-0 rounded-lg object-cover sm:block"
              />
              <div className="min-w-0 space-y-1.5">
                <p className={`flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide ${copy.accent}`}>
                  <Icon className="h-3.5 w-3.5" aria-hidden="true" />
                  {copy.label}
                </p>
                <DialogTitle className="line-clamp-2 text-lg font-bold leading-snug">{article.title}</DialogTitle>
                <DialogDescription className="flex flex-wrap items-center gap-x-2 text-xs">
                  <span>{article.source?.name || "Publisher"}</span>
                  {published && isValid(published) && <span>· {format(published, "MMM d, yyyy")}</span>}
                  <a href={article.url} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1 font-medium text-primary hover:underline">
                    · Read original <ExternalLink className="h-3 w-3" aria-hidden="true" />
                  </a>
                </DialogDescription>
              </div>
            </header>

            <div className="flex-1 overflow-y-auto px-5 py-6 sm:px-8" aria-live="polite" aria-busy={loading}>
              {!isAuthenticated ? (
                <div className="flex flex-col items-center gap-4 py-10 text-center">
                  <span className="rounded-full bg-muted p-4"><Lock className="h-6 w-6 text-muted-foreground" aria-hidden="true" /></span>
                  <p className="max-w-sm text-sm text-muted-foreground">{copy.signIn}</p>
                  <div className="flex gap-2">
                    <Button asChild><Link href="/login?next=/news" onClick={onClose}>Sign in</Link></Button>
                    <Button asChild variant="outline"><Link href="/register" onClick={onClose}>Create account</Link></Button>
                  </div>
                </div>
              ) : loading ? (
                <LoadingState message={copy.loading} />
              ) : error ? (
                <div role="alert" className="flex flex-col items-start gap-3 rounded-lg border border-destructive/30 bg-destructive/5 p-4 text-sm">
                  <p className="flex items-center gap-2 font-medium text-destructive">
                    <AlertCircle className="h-4 w-4" aria-hidden="true" />
                    {error}
                  </p>
                  <Button size="sm" variant="outline" onClick={onRetry}>
                    <RotateCcw className="mr-2 h-3.5 w-3.5" aria-hidden="true" /> Try again
                  </Button>
                </div>
              ) : hasResult ? (
                <>
                  {basis === "summary_only" && (
                    <p className="mb-5 flex items-start gap-2 rounded-lg bg-amber-50 p-3 text-xs text-amber-950 dark:bg-amber-950/40 dark:text-amber-200">
                      <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden="true" />
                      The publisher&apos;s full text wasn&apos;t available, so this is based on the headline and summary only.
                    </p>
                  )}
                  {mode === "forecast" && forecast ? (
                    <ForecastView forecast={forecast} />
                  ) : (
                    <div className="prose prose-zinc max-w-none dark:prose-invert prose-headings:mb-2 prose-headings:mt-6 prose-h3:text-base prose-h3:font-semibold first:prose-headings:mt-0">
                      <ReactMarkdown>{explanation}</ReactMarkdown>
                    </div>
                  )}
                </>
              ) : null}
            </div>

            {isAuthenticated && (
              <footer className="border-t px-5 py-3">
                <p className="text-xs text-muted-foreground">{copy.disclaimer}</p>
              </footer>
            )}
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}
